import Link from "next/link";
import type { Route } from "next";
import { DocumentArrowDownIcon } from "@heroicons/react/24/outline";
import { formatCurrency, formatDate } from "@/lib/utils";
import { INVOICE_TYPE_CLASSES, INVOICE_TYPE_LABELS } from "@/lib/invoice/labels";
import type { AdminInvoice } from "@/actions/invoices/getInvoicesAction";
import type { RevenueStats } from "@/actions/stats/getRevenueStatsAction";

type InvoiceManagementProps = {
  invoices: AdminInvoice[];
  /** Null when the stats query failed; the list still renders */
  revenue: RevenueStats | null;
};

const ACCENTS = {
  gold: "border-gold/20 hover:border-gold/40 text-white",
  blue: "border-blue-500/20 hover:border-blue-500/40 text-blue-400",
  green: "border-green-500/20 hover:border-green-500/40 text-green-400",
} as const;

function StatCard({
  label,
  value,
  accent,
  hint,
}: {
  label: string;
  value: string | number;
  accent: keyof typeof ACCENTS;
  hint?: string;
}) {
  return (
    <div
      className={`bg-linear-to-br from-gray-800/80 to-gray-900/80 border rounded-xl p-4 sm:p-6 shadow-lg shadow-black/20 transition-colors duration-300 ${ACCENTS[accent]}`}
    >
      <h3 className="text-gray-400 text-xs sm:text-sm mb-2 font-medium">{label}</h3>
      <p className="text-2xl sm:text-3xl font-iceland">{value}</p>
      {hint ? <p className="text-xs text-gray-500 mt-1">{hint}</p> : null}
    </div>
  );
}

function Th({ children, className = "" }: { children: React.ReactNode; className?: string }) {
  return (
    <th
      className={`px-4 sm:px-6 py-3 sm:py-4 text-xs sm:text-sm font-semibold text-gold uppercase tracking-wider ${className}`}
    >
      {children}
    </th>
  );
}

const button =
  "inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-medium border transition-colors bg-gray-700/40 text-gray-200 border-gray-600 hover:bg-gray-700/70";

/**
 * Every invoice generated by the Stripe webhook, newest first. Revenue comes
 * from the paid charges (same figure as the dashboard), not from the invoices.
 */
export default function InvoiceManagement({ invoices, revenue }: InvoiceManagementProps) {
  let deposits = 0;
  let finals = 0;
  for (const invoice of invoices) {
    if (invoice.type === "initial") deposits++;
    else if (invoice.type === "final") finals++;
  }

  return (
    <div className="space-y-6 sm:space-y-8 px-4 sm:px-6 lg:px-8 py-4 sm:py-6 font-inter">
      <div>
        <h1 className="text-3xl sm:text-4xl md:text-5xl text-gold font-iceland mb-2">Invoices</h1>
        <p className="text-base sm:text-lg text-gray-400">
          Generated automatically when a payment clears and emailed to the customer.
        </p>
      </div>

      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4 sm:gap-6">
        <StatCard label="Total invoices" value={invoices.length} accent="gold" />
        <StatCard label="Deposit invoices" value={deposits} accent="blue" />
        <StatCard label="Final invoices" value={finals} accent="green" />
        <StatCard
          label="Total revenue"
          value={revenue ? formatCurrency(revenue.totalRevenue) : "—"}
          accent="gold"
          hint={revenue ? `${formatCurrency(revenue.thisMonthRevenue)} this month` : undefined}
        />
      </div>

      <div className="bg-linear-to-br from-gray-800/80 to-gray-900/80 border border-gray-700/50 rounded-xl overflow-hidden shadow-xl shadow-black/20">
        {invoices.length === 0 ? (
          <div className="p-10 text-center text-gray-400">
            <p className="mb-2">No invoices yet.</p>
            <p className="text-sm text-gray-500">
              An invoice is created for each deposit and final payment, plus a summary when a{" "}
              <Link href="/projects" className="text-gold hover:underline">
                project
              </Link>{" "}
              is fully paid.
            </p>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full">
              <thead>
                <tr className="bg-linear-to-r from-gray-700/80 to-gray-800/80 text-left border-b border-gray-700/50">
                  <Th>Invoice</Th>
                  <Th>Customer</Th>
                  <Th className="hidden md:table-cell">Project</Th>
                  <Th>Amount</Th>
                  <Th className="hidden sm:table-cell">Issued</Th>
                  <Th>Actions</Th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-700/30">
                {invoices.map((invoice) => {
                  const projectHref = `/projects/${invoice.projectId}` as Route;
                  return (
                    <tr key={invoice.id} className="hover:bg-gray-700/20 transition-colors">
                      <td className="px-4 sm:px-6 py-4 align-top">
                        <div className="font-mono text-sm font-semibold text-gold whitespace-nowrap">
                          {invoice.invoiceNumber}
                        </div>
                        <span
                          className={`mt-1 inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-semibold border whitespace-nowrap ${INVOICE_TYPE_CLASSES[invoice.type]}`}
                        >
                          {INVOICE_TYPE_LABELS[invoice.type]}
                        </span>
                        <div className="sm:hidden text-xs text-gray-500 mt-1">{formatDate(invoice.issueDate)}</div>
                      </td>
                      <td className="px-4 sm:px-6 py-4 align-top">
                        <div className="text-sm text-white font-semibold">{invoice.customerName}</div>
                        <div className="text-xs text-gray-400 truncate max-w-[160px] sm:max-w-none">
                          {invoice.customerEmail}
                        </div>
                        <div className="md:hidden text-xs text-gray-500 mt-1">
                          <Link href={projectHref} className="font-mono hover:text-gold">
                            {invoice.projectCode}
                          </Link>
                        </div>
                      </td>
                      <td className="hidden md:table-cell px-6 py-4 align-top">
                        <Link href={projectHref} className="font-mono text-sm text-white hover:text-gold">
                          {invoice.projectCode}
                        </Link>
                        <div className="text-xs text-gray-500 mt-1">{invoice.planName}</div>
                      </td>
                      <td className="px-4 sm:px-6 py-4 align-top">
                        <div className="text-sm text-white font-semibold whitespace-nowrap">
                          {formatCurrency(invoice.total)}
                        </div>
                        {invoice.taxAmount > 0 ? (
                          <div className="text-xs text-gray-500 mt-1">Tax {formatCurrency(invoice.taxAmount)}</div>
                        ) : null}
                        {invoice.status !== "paid" ? (
                          <div className="text-xs text-yellow-400 mt-1 capitalize">{invoice.status}</div>
                        ) : null}
                      </td>
                      <td className="hidden sm:table-cell px-6 py-4 align-top text-sm text-gray-300 whitespace-nowrap">
                        {formatDate(invoice.issueDate)}
                      </td>
                      <td className="px-4 sm:px-6 py-4 align-top">
                        <div className="flex flex-wrap gap-2">
                          {invoice.pdfUrl ? (
                            <a href={invoice.pdfUrl} target="_blank" rel="noopener noreferrer" className={button}>
                              <DocumentArrowDownIcon className="w-4 h-4" aria-hidden="true" />
                              PDF
                            </a>
                          ) : (
                            <span className="text-xs text-gray-500 self-center">No PDF</span>
                          )}
                          <Link href={projectHref} className={button}>
                            Project
                          </Link>
                        </div>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
