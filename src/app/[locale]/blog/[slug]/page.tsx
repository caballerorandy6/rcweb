import { notFound } from "next/navigation";
import { genPageMetadata } from "@/utils/genPageMetadata";
import { JsonLdForBreadcrumb } from "@/components/seo/JsonLdForBreadcrumb";
import { JsonLdForArticle } from "@/components/seo/JsonLdForArticle";
import { siteConfig } from "@/config/site";
import { getPostBySlug, getAllSlugs } from "@/lib/blog";
import BlogPost from "@/components/blog/BlogPost";

interface BlogPostPageProps {
  params: Promise<{
    slug: string;
  }>;
}

export async function generateStaticParams() {
  const slugs = getAllSlugs();
  return slugs.map((slug) => ({
    slug,
  }));
}

export async function generateMetadata({ params }: BlogPostPageProps) {
  const { slug } = await params;
  const post = getPostBySlug(slug);

  if (!post) {
    return genPageMetadata({
      title: "Post Not Found",
      description: "The blog post you're looking for doesn't exist.",
      pageRoute: "/blog",
    });
  }

  return genPageMetadata({
    title: post.title,
    description: post.description,
    pageRoute: `/blog/${slug}`,
    article: {
      publishedTime: post.date,
      modifiedTime: post.updated,
      authors: [post.author],
      tags: post.tags,
    },
  });
}

export default async function BlogPostPage({ params }: BlogPostPageProps) {
  const { slug } = await params;
  const post = getPostBySlug(slug);

  if (!post) {
    notFound();
  }

  const postUrl = `${siteConfig.baseUrl}/blog/${slug}`;

  return (
    <>
      <JsonLdForBreadcrumb
        itemList={[
          { name: "Home", item: siteConfig.baseUrl },
          { name: "Blog", item: `${siteConfig.baseUrl}/blog` },
          { name: post.title, item: postUrl },
        ]}
      />
      <JsonLdForArticle
        url={postUrl}
        headline={post.title}
        description={post.description}
        // The card generated by opengraph-image.tsx next to this page
        image={`${postUrl}/opengraph-image`}
        datePublished={post.date}
        dateModified={post.updated ?? post.date}
        keywords={post.tags}
        author={{
          name: siteConfig.author.name,
          url: `${siteConfig.baseUrl}/about`,
        }}
      />
      <BlogPost post={post} />
    </>
  );
}
